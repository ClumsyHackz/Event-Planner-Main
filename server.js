require('dotenv').config();
const express = require('express');
const path = require('path');
const fs = require('fs');
const store = require('./lib/store');
const authRoutes = require('./routes/auth');
const eventRoutes = require('./routes/events');
const organizerRoutes = require('./routes/organizer');
const adminRoutes = require('./routes/admin');
const app = express();
app.use(express.json({ limit: '1mb' }));
app.use(express.urlencoded({ extended: true }));
app.use(express.static(path.join(__dirname, 'website')));
app.get('/api/health', (_req,res) => res.json({ok:true,database:'local-json',storageFile:'data/db.json'}));
app.use('/api/auth', authRoutes);
app.use('/api/events', eventRoutes);
app.use('/api/organizer', organizerRoutes);
app.use('/api/admin', adminRoutes);
app.get('/', (_req,res) => res.sendFile(path.join(__dirname,'website','index.html')));
app.use((err,_req,res,_next) => { console.error(err.message); if(err.code==='11000') return res.status(409).json({error:'A record with that value already exists'}); res.status(err.status||500).json({error:err.status?err.message:'Unexpected server error'}); });
const port=process.env.PORT||3000;
fs.mkdirSync(path.join(__dirname,'data'),{recursive:true});
app.listen(port,'0.0.0.0',()=>console.log(`Event Planner running at http://localhost:${port} (local JSON database)`));
